import logging
import re
import time
from dataclasses import dataclass

from playwright.sync_api import Page

from .browser import page_has_security_challenge


log = logging.getLogger(__name__)

JOB_SEARCH_URL = (
    "https://www.jobsatamazon.co.uk/app#/jobSearch?"
    "query=Warehouse%20Associate&postal=&locale=en-GB"
)

# Amazon can prefix the role name, e.g. "Delivery Station Warehouse Associate".
# Keep the match focused on role titles rather than requiring one exact wording.
WAREHOUSE_TITLE_RE = re.compile(
    r"^\s*(?:[A-Za-z][A-Za-z&/'-]*\s+){0,5}Warehouse Associate\s*$",
    re.I,
)
APPLY_RE = re.compile(r"^\s*Apply\s*$", re.I)
NEXT_RE = re.compile(r"^\s*Next\s*$", re.I)
START_APPLICATION_RE = re.compile(r"^\s*Start Application\s*$", re.I)
CONTINUE_RE = re.compile(r"^\s*Continue\s*$", re.I)
BLOCKED_PAGE_RE = re.compile(
    r"(403\s+ERROR|request could not be satisfied|request blocked|generated by cloudfront)",
    re.I,
)
MULTIPLE_LOCATIONS_RE = re.compile(
    r"multiple\s+on[- ]?site\s+locations?\s+available",
    re.I,
)


@dataclass
class JobCandidate:
    index: int
    title: object
    card: object
    text: str
    location: str | None


def extract_reported_job_count(text: str) -> int | None:
    """Read Amazon's '20 jobs found' style result count when present."""
    match = re.search(r"\b(\d+)\s+jobs?\s+found\b", text, re.I)
    return int(match.group(1)) if match else None


def read_reported_job_count(page: Page) -> int | None:
    try:
        body = page.locator("body").inner_text(timeout=2500)
    except Exception:
        return None
    return extract_reported_job_count(body)


def job_candidate_key(candidate: JobCandidate) -> str:
    """Return a stable key for one result card across scroll/lazy-load cycles."""
    try:
        link = candidate.card.locator("a").first
        if link.count():
            href = link.get_attribute("href")
            if href:
                return "href:" + href.strip().casefold()
    except Exception:
        pass

    return "text:" + " ".join(candidate.text.split()).casefold()


def reset_job_search_scroll(page: Page) -> None:
    """Return Amazon's job-result page and any inner result scroller to the top."""
    try:
        page.evaluate(
            """() => {
                const nodes = [
                    document.scrollingElement,
                    ...document.querySelectorAll(
                        'main, [role="main"], section, div, ul'
                    )
                ].filter(Boolean);

                const seen = new Set();
                for (const node of nodes) {
                    if (seen.has(node)) continue;
                    seen.add(node);

                    const text = (node.innerText || '').toLowerCase();
                    const scrollable =
                        node.scrollHeight > node.clientHeight + 40;

                    if (
                        node === document.scrollingElement ||
                        (scrollable && text.includes('warehouse associate'))
                    ) {
                        node.scrollTop = 0;
                    }
                }
                window.scrollTo(0, 0);
            }"""
        )
        page.wait_for_timeout(200)
    except Exception:
        pass


def scroll_job_search_results(page: Page) -> bool:
    """Scroll Amazon's actual job-result container by one viewport.

    Amazon can place the cards inside an inner scrollable container instead of
    the document scrollbar. Search every plausible scroll container, prioritize
    one containing Warehouse Associate results, and move the first one that still
    has content below it.
    """
    try:
        result = page.evaluate(
            """() => {
                const root = document.scrollingElement || document.documentElement;
                const rawNodes = [
                    root,
                    ...document.querySelectorAll(
                        'main, [role="main"], section, div, ul'
                    )
                ].filter(Boolean);

                const seen = new Set();
                const candidates = [];

                for (const node of rawNodes) {
                    if (seen.has(node)) continue;
                    seen.add(node);

                    const clientHeight = node.clientHeight || 0;
                    const scrollHeight = node.scrollHeight || 0;
                    const max = Math.max(0, scrollHeight - clientHeight);
                    const before = node.scrollTop || 0;
                    const remaining = Math.max(0, max - before);

                    if (clientHeight < 120 || max < 40 || remaining < 5) {
                        continue;
                    }

                    const text = (node.innerText || '').toLowerCase();
                    let score = remaining;

                    if (text.includes('warehouse associate')) {
                        score += 1000000;
                    }
                    if (/\d+\s+jobs?\s+found/i.test(text)) {
                        score += 500000;
                    }
                    if (node === root) {
                        score += 1000;
                    }

                    candidates.push({
                        node,
                        before,
                        max,
                        remaining,
                        clientHeight,
                        score
                    });
                }

                candidates.sort((a, b) => b.score - a.score);

                for (const candidate of candidates) {
                    const step = Math.max(
                        Math.floor(candidate.clientHeight * 0.80),
                        450
                    );
                    const target = Math.min(
                        candidate.before + step,
                        candidate.max
                    );

                    candidate.node.scrollTop = target;
                    const after = candidate.node.scrollTop || 0;

                    if (after > candidate.before) {
                        return {
                            moved: true,
                            before: candidate.before,
                            after,
                            max: candidate.max,
                            remaining: Math.max(0, candidate.max - after)
                        };
                    }
                }

                return {moved: false};
            }"""
        )
        page.wait_for_timeout(450)
        return bool(result and result.get("moved"))
    except Exception:
        return False


def normalise_location_terms(raw: str) -> list[str]:
    """Return comma-separated location alternatives in normalized form."""
    result = []
    for value in raw.split(","):
        compact = " ".join(value.split()).strip()
        if compact and compact.casefold() not in {item.casefold() for item in result}:
            result.append(compact)
    return result


def text_matches_location(text: str, desired_locations: list[str]) -> bool:
    """Treat configured locations as alternatives; no locations means accept any."""
    if not desired_locations:
        return True
    haystack = " ".join(text.split()).casefold()
    return any(term.casefold() in haystack for term in desired_locations)


def card_requires_detail_location_check(text: str) -> bool:
    """Only ambiguous multi-location cards need opening to discover their site."""
    compact = " ".join(text.split())
    return bool(MULTIPLE_LOCATIONS_RE.search(compact))


def extract_card_location(raw_text: str) -> str | None:
    """Extract the visible place line from one Amazon search-result card."""
    if card_requires_detail_location_check(raw_text):
        return None

    lines = [" ".join(line.split()).strip() for line in raw_text.splitlines()]
    lines = [line for line in lines if line]
    if not lines:
        return None

    ignored_prefixes = (
        "type:",
        "duration:",
        "pay rate:",
        "job id:",
        "schedule:",
        "start date:",
        "end date:",
        "hours:",
    )

    candidates = []
    for line in lines:
        lower = line.casefold()
        if "warehouse associate" in lower:
            continue
        if lower.startswith(ignored_prefixes):
            continue
        if lower in {"apply", "share"}:
            continue
        candidates.append(line)

    if not candidates:
        return None

    # The Amazon card layout shown by the site places the visible location last.
    location = candidates[-1]
    if len(location) > 160:
        return None
    return location


def page_is_blocked(page: Page) -> bool:
    try:
        title = page.title()
    except Exception:
        title = ""
    try:
        body = page.locator("body").inner_text(timeout=2500)
    except Exception:
        body = ""
    return bool(BLOCKED_PAGE_RE.search(f"{title}\n{body}"))


def _visible_first(locator):
    try:
        count = locator.count()
    except Exception:
        return None

    for index in range(count):
        item = locator.nth(index)
        try:
            if item.is_visible():
                return item
        except Exception:
            continue
    return None


def _card_ancestor(title):
    """Find a compact ancestor representing one Warehouse Associate result card."""
    best = None
    best_text = ""

    for depth in range(1, 9):
        try:
            ancestor = title.locator("xpath=" + "/.." * depth)
            text = " ".join(ancestor.inner_text(timeout=1200).split())
        except Exception:
            continue

        if not text or len(text) > 2500:
            continue

        if "warehouse associate" not in text.casefold():
            continue

        # Prefer an ancestor that also contains job metadata or a location indicator.
        looks_like_job = bool(
            re.search(
                r"(Full Time|Part Time|Reduced|Flexible|Pay rate|Duration|"
                r"multiple on site locations available|Work address|Job ID|£\s*\d)",
                text,
                re.I,
            )
        )
        if looks_like_job:
            return ancestor, text

        if best is None or len(text) < len(best_text):
            best = ancestor
            best_text = text

    if best is not None:
        return best, best_text

    try:
        parent = title.locator("xpath=..")
        return parent, " ".join(parent.inner_text(timeout=1200).split())
    except Exception:
        return title, ""


def read_warehouse_job_cards(page: Page) -> list[JobCandidate]:
    """Read visible Warehouse Associate result cards without clicking Apply."""
    titles = page.get_by_text(WAREHOUSE_TITLE_RE)
    cards = []
    seen = set()

    try:
        count = titles.count()
    except Exception:
        return cards

    for index in range(count):
        title = titles.nth(index)
        try:
            if not title.is_visible():
                continue
        except Exception:
            continue

        card, text = _card_ancestor(title)
        try:
            raw_card_text = card.inner_text(timeout=1200)
        except Exception:
            raw_card_text = text
        location = extract_card_location(raw_card_text)

        signature = " ".join(text.split()).casefold()
        if not signature or signature in seen:
            continue
        seen.add(signature)

        cards.append(
            JobCandidate(
                index=len(cards),
                title=title,
                card=card,
                text=text,
                location=location,
            )
        )

    return cards


def _find_visible_button(page: Page, pattern: re.Pattern):
    button = _visible_first(page.get_by_role("button", name=pattern))
    if button is not None:
        return button
    return _visible_first(
        page.locator("button, [role='button']").filter(has_text=pattern)
    )


def find_apply_button(page: Page):
    """Return a visible Apply button on a job-details page, if present."""
    return _find_visible_button(page, APPLY_RE)


def find_next_button(page: Page):
    return _find_visible_button(page, NEXT_RE)


def find_start_application_button(page: Page):
    return _find_visible_button(page, START_APPLICATION_RE)


def find_continue_button(page: Page):
    return _find_visible_button(page, CONTINUE_RE)


def find_confirm_selection_button(page: Page):
    return _find_visible_button(page, CONFIRM_SELECTION_RE)


def find_submit_application_button(page: Page):
    return _find_visible_button(page, SUBMIT_APPLICATION_RE)


def click_confirm_selection(page: Page, timeout_seconds: float = 8.0) -> bool:
    button = find_confirm_selection_button(page)
    if button is None:
        return False

    try:
        button.click(timeout=5000)
    except Exception:
        return False

    deadline = time.monotonic() + max(1.0, timeout_seconds)
    while time.monotonic() < deadline:
        if find_submit_application_button(page) is not None:
            return True
        time.sleep(0.15)

    return False


def find_open_application_tab(page: Page):
    """Return the newest open Amazon application tab in this browser context."""
    try:
        pages = list(page.context.pages)
    except Exception:
        return None

    for candidate in reversed(pages):
        try:
            if candidate.is_closed():
                continue
            if "/application/uk/" in candidate.url.lower():
                return candidate
        except Exception:
            continue

    return None


def click_application_stage(page: Page, stage: str) -> Page | None:
    """Click one Method 2 action exactly once and return the page to control next.

    Amazon may open a new tab for an application step. We switch to that tab once,
    but the caller is responsible for never re-clicking the same stage until the
    application state changes.
    """
    button = None

    if stage == "APPLY":
        button = find_apply_button(page)
    elif stage == "NEXT":
        button = find_next_button(page)
    elif stage == "START_APPLICATION":
        button = find_start_application_button(page)
    elif stage == "CONTINUE":
        button = find_continue_button(page)
    else:
        return None

    if button is None:
        return None

    context = page.context
    existing_pages = list(context.pages)
    previous_url = page.url

    button.click(timeout=7000)

    # Return as soon as Amazon creates the next tab. Do not wait several more
    # seconds for DOMContentLoaded here; the main state loop can wait for the next
    # button while the new page finishes rendering.
    deadline = time.monotonic() + 3
    next_page = page

    while time.monotonic() < deadline:
        try:
            new_pages = [
                candidate
                for candidate in context.pages
                if candidate not in existing_pages and not candidate.is_closed()
            ]
        except Exception:
            new_pages = []

        if new_pages:
            next_page = new_pages[-1]
            break

        application_tab = find_open_application_tab(page)
        if application_tab is not None and application_tab is not page:
            next_page = application_tab
            break

        try:
            if page.is_closed():
                break
            if page.url != previous_url:
                next_page = page
                break
        except Exception:
            break

        time.sleep(0.05)

    try:
        next_page.bring_to_front()
    except Exception:
        pass

    # If an application step replaced an older application tab with a new one,
    # close only the superseded application tab. Keep the original job-details tab.
    if next_page is not page:
        try:
            old_url = page.url.lower()
            if "/application/uk/" in old_url:
                page.close()
        except Exception:
            pass

    return next_page


def shift_selection_page_visible(page: Page) -> bool:
    """Detect the actual shift-selection page, not a normal job-details page."""
    try:
        body = page.locator("body").inner_text(timeout=3000)
    except Exception:
        return False

    compact = " ".join(body.split())

    # Job-details pages can also contain words such as Start date, Shift,
    # Pay rate, Hours and Location. Require a shift-selection-specific signal too.
    strong_signal = bool(
        re.search(
            r"(Select\s+(?:a|your|work)\s+shift|"
            r"Choose\s+(?:a|your|work)\s+shift|"
            r"Showing\s+\d+\s+of\s+\d+\s+shifts?)",
            compact,
            re.I,
        )
    )
    if not strong_signal:
        return False

    markers = [
        r"\bStart date\b",
        r"\bEnd date\b",
        r"\bShift\b",
        r"\bPay rate\b",
        r"\bHours\b",
        r"\bLocation\b",
    ]
    return sum(bool(re.search(marker, compact, re.I)) for marker in markers) >= 3


def detect_application_stage(page: Page) -> str:
    """Identify the next application stage after a matching job is opened."""
    if page_has_security_challenge(page):
        return "SECURITY_CHECK"

    try:
        url = page.url.lower()
    except Exception:
        url = ""

    # Amazon uses /nhe for the New Hire Event / pre-hire appointment stage.
    # Detect it before generic button matching so this page is never treated as
    # an unknown application state.
    if find_submit_application_button(page) is not None:
        return "SUBMIT_APPLICATION"

    if "#/nhe" in url:
        return "APPOINTMENT_SELECTION"

    # Prefer visible action buttons over generic page text. This lets the
    # post-offer Additional Information page use its own visible Next button,
    # even when a scheduleId is already present in the URL.
    if find_continue_button(page) is not None:
        return "CONTINUE"
    if find_start_application_button(page) is not None:
        return "START_APPLICATION"
    if find_next_button(page) is not None:
        return "NEXT"
    if find_apply_button(page) is not None:
        return "APPLY"
    if shift_selection_page_visible(page):
        return "SHIFT_SELECTION"

    if "#/additional-information" in url and "scheduleid=" in url:
        return "POST_SHIFT"

    return "UNKNOWN"


def _fill_warehouse_search_if_available(page: Page) -> None:
    """Best-effort UI alignment with the documented search settings."""
    candidates = [
        page.get_by_role("textbox", name=re.compile(r"(search|job)", re.I)),
        page.locator(
            'input[placeholder*="search" i], input[aria-label*="search" i]'
        ),
    ]

    for locator in candidates:
        field = _visible_first(locator)
        if field is None:
            continue
        try:
            current = field.input_value(timeout=1200)
        except Exception:
            current = ""

        if "warehouse associate" in current.casefold():
            return

        try:
            field.fill("Warehouse Associate", timeout=2500)
            page.keyboard.press("Enter")
            page.wait_for_timeout(500)
            return
        except Exception:
            continue


def _select_all_jobs_if_available(page: Page) -> None:
    """Best-effort selection of Amazon's All job-search option."""
    candidates = [
        page.get_by_role("button", name=re.compile(r"^\s*All\s*$", re.I)),
        page.get_by_text(re.compile(r"^\s*All\s*$", re.I)),
    ]

    for locator in candidates:
        item = _visible_first(locator)
        if item is None:
            continue
        try:
            item.click(timeout=2000)
            page.wait_for_timeout(250)
            return
        except Exception:
            continue


def open_job_search(page: Page) -> None:
    """Open the Warehouse Associate search page and align visible search controls."""
    page.goto(JOB_SEARCH_URL, wait_until="domcontentloaded")

    if page_has_security_challenge(page):
        raise RuntimeError("Amazon security/verification challenge detected.")

    if page_is_blocked(page):
        raise RuntimeError("Amazon returned a 403 / request-blocked page.")

    _select_all_jobs_if_available(page)
    _fill_warehouse_search_if_available(page)
    page.wait_for_timeout(700)


def open_job_candidate(page: Page, candidate: JobCandidate) -> None:
    """Open one result card without clicking the Apply button."""
    previous_url = page.url

    try:
        candidate.title.click(timeout=5000)
    except Exception:
        candidate.card.click(timeout=5000)

    try:
        page.wait_for_load_state("domcontentloaded", timeout=8000)
    except Exception:
        pass
    page.wait_for_timeout(500)

    if page.url == previous_url and find_apply_button(page) is None:
        # Some SPA cards need their nearest link rather than the title text itself.
        try:
            link = candidate.card.locator("a").first
            if link.count() and link.is_visible():
                link.click(timeout=4000)
                page.wait_for_timeout(500)
        except Exception:
            pass


def read_job_detail_text(page: Page) -> str:
    try:
        return " ".join(page.locator("body").inner_text(timeout=3000).split())
    except Exception:
        return ""


def return_to_job_search(page: Page) -> None:
    """Return reliably to the documented Warehouse Associate result page."""
    open_job_search(page)


def wait_for_manual_login(page: Page) -> None:
    """Pause while the user signs in and completes any verification manually."""
    open_job_search(page)

    print("\n" + "=" * 72)
    print("AMAZON JOB SEARCH METHOD - MANUAL LOGIN")
    print("1. Use the Brave window to sign in to Amazon Jobs.")
    print("2. Complete any OTP, CAPTCHA, security or identity check manually.")
    print("3. Return to the Warehouse Associate search page.")
    print("4. Return to this terminal and press Enter.")
    print("=" * 72 + "\n")

    input("Press Enter AFTER Amazon Jobs login is complete: ")

    if page.is_closed():
        raise RuntimeError("The Amazon Jobs tab was closed during manual login.")

    if page_has_security_challenge(page):
        raise RuntimeError(
            "Amazon still shows a security/verification step. Complete it manually first."
        )

    open_job_search(page)
