ROOT = Path(__file__).resolve().parent.parent
LOG_DIR = ROOT / "logs"
SCREENSHOT_DIR = ROOT / "screenshots"
BLOCKED_RETRY_SECONDS = 60

EMPTY_SCHEDULE_RE = re.compile(
    r"(Sorry,\s*we do not have any schedules matching your preferences(?:\.\s*"
    r"We post schedules from Monday to Friday each week\.\s*"
    r"Please try again at a later time\.)?"
    r"|We do not have any schedules available at this time\.\s*"
    r"Please try again later or contact Candidate Support)",
    re.I,
)
SHIFT_COUNT_RE = re.compile(r"Showing\s+\d+\s+of\s+\d+\s+shifts?", re.I)
SHIFT_HOURS_RE = re.compile(
    r"\bHours:\s*(\d+(?:\.\d+)?)\s*hours?\s*/\s*week\b",
    re.I,
)
BLOCKED_PAGE_RE = re.compile(
    r"(403\s+ERROR|request could not be satisfied|request blocked|generated by cloudfront)",
    re.I,
)


def setup_logging():
    LOG_DIR.mkdir(exist_ok=True)
    log_path = LOG_DIR / "shift-catcher.log"
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        handlers=[
            logging.StreamHandler(),
            logging.FileHandler(log_path, encoding="utf-8"),
        ],
    )


def load_config():
    config_path = ROOT / "config.json"
    if not config_path.exists():
        raise FileNotFoundError(
            "config.json not found. Copy config.example.json to config.json first."
        )
    return json.loads(config_path.read_text(encoding="utf-8"))


def choose_desired_hours(default_hours: float) -> float:
    options = {"1": 10.0, "2": 20.0, "3": 30.0, "4": 40.0}
    direct_values = {10.0, 20.0, 30.0, 40.0}

    print("\n" + "=" * 58)
    print("AMAZON SHIFT CATCHER - DESIRED HOURS")
    print("Choose the maximum weekly hours for this run:")
    print("  1. Up to 10 hours")
    print("  2. Up to 20 hours")
    print("  3. Up to 30 hours")
    print("  4. Up to 40 hours")
    print(f"Press Enter to keep config default: Up to {default_hours:g} hours")
    print("=" * 58)

    while True:
        choice = input("Select 1-4 (or type 10/20/30/40): ").strip()
        if choice == "":
            selected = float(default_hours)
            break
        if choice in options:
            selected = options[choice]
            break
        try:
            typed = float(choice)
        except ValueError:
            typed = -1
        if typed in direct_values:
            selected = typed
            break
        print("Invalid choice. Please select 1, 2, 3, 4, or type 10/20/30/40.")

    print(f"\nSelected: Up to {selected:g} hours/week")
    print("Starting monitor...\n")
    return selected


def env_bool(name: str, default: bool = False) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def timestamp_name(prefix: str) -> Path:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    return SCREENSHOT_DIR / f"{prefix}-{stamp}.png"


def shift_live_screenshot_name(index: int) -> Path:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    return SCREENSHOT_DIR / f"shift-live-{index:04d}-{stamp}.png"


def choose_amazon_page(browser, my_jobs_url: str):
    pages = []
    for context in browser.contexts:
        pages.extend(context.pages)
    for page in pages:
        try:
            if "jobsatamazon.co.uk" in page.url.lower():
                return page
        except Exception:
            pass
    if not browser.contexts:
        raise RuntimeError("No browser context found in the attached Brave session.")
    context = browser.contexts[0]
    page = context.new_page()
    page.goto(my_jobs_url, wait_until="domcontentloaded")
    return page


def get_page_status(page) -> tuple[str, str, str | None, str]:
    try:
        url = page.url
    except Exception:
        url = "<unavailable>"
    try:
        title = " ".join(page.title().split()) or "<no title>"
    except Exception:
        title = "<unavailable>"

    empty_state = None
    excerpt = "<unavailable>"
    try:
        body_text = page.locator("body").inner_text(timeout=3000)
        normalized = " ".join(body_text.split())
        excerpt = normalized[:500] if normalized else "<empty body>"
        match = EMPTY_SCHEDULE_RE.search(body_text)
        if match:
            empty_state = " ".join(match.group(0).split())
    except Exception:
        pass
    return url, title, empty_state, excerpt


def get_blocked_page_status(page) -> tuple[bool, str]:
    try:
        title = page.title()
    except Exception:
        title = ""
    try:
        body_text = page.locator("body").inner_text(timeout=3000)
    except Exception:
        body_text = ""

    combined = f"{title}\n{body_text}"
    blocked = bool(BLOCKED_PAGE_RE.search(combined))
    excerpt = " ".join(body_text.split())[:500]
    return blocked, excerpt


def recover_from_403(page, log, excerpt: str) -> bool:
    """Pause all normal monitoring and test recovery once every 60 seconds."""
    started_at = datetime.now()
    started_monotonic = time.monotonic()
    attempt = 0

    log.error(
        "Amazon returned a 403/CloudFront blocked page at %s. "
        "Normal monitoring is paused.",
        started_at.strftime("%Y-%m-%d %H:%M:%S"),
    )
    if excerpt:
        log.error("Blocked-page excerpt: %s", excerpt)

    try:
        if not page.is_closed():
            save_screenshot(page, timestamp_name("amazon-403-blocked"))
    except Exception:
        pass

    send_notification(
        "Amazon returned a 403 / Request blocked page.\n"
        "Normal monitoring is PAUSED.\n"
        f"The catcher will wait {BLOCKED_RETRY_SECONDS} seconds, then make one recovery test.\n"
        "If the page is still blocked it will wait another 60 seconds before testing again.",
        title="Amazon 403 - recovery mode",
        priority=5,
    )

    while True:
        attempt += 1
        log.warning(
            "403 recovery attempt %s: no requests for %s seconds, then one test reload.",
            attempt,
            BLOCKED_RETRY_SECONDS,
        )
        time.sleep(BLOCKED_RETRY_SECONDS)

        if page.is_closed():
            log.error("Amazon tab was closed during 403 recovery.")
            return False

        try:
            page.reload(wait_until="domcontentloaded", timeout=30000)
        except Exception as exc:
            log.exception("403 recovery test reload failed: %s", exc)
            send_notification(
                f"Amazon 403 recovery test failed with a page error:\n{exc}\n\n"
                "Automatic monitoring has stopped. Check the page manually.",
                title="Amazon 403 recovery stopped",
                priority=5,
            )
            return False

        blocked, latest_excerpt = get_blocked_page_status(page)
        if blocked:
            log.warning(
                "403 is still present after recovery attempt %s. Waiting another %s seconds.",
                attempt,
                BLOCKED_RETRY_SECONDS,
            )
            if latest_excerpt:
                log.debug("Blocked-page excerpt: %s", latest_excerpt)
            continue

        try:
            wait_for_schedule_settled(page)
        except Exception as exc:
            log.warning("Page returned from 403 but did not settle normally yet: %s", exc)

        blocked, latest_excerpt = get_blocked_page_status(page)
        if blocked:
            log.warning(
                "403 returned while verifying recovery. Waiting another %s seconds.",
                BLOCKED_RETRY_SECONDS,
            )
            continue

        elapsed = int(time.monotonic() - started_monotonic)
        log.warning(
            "403 RECOVERED after %s seconds and %s recovery test(s).",
            elapsed,
            attempt,
        )
        send_notification(
            f"Amazon page recovered from the 403 after about {elapsed} seconds.\n"
            "The hours filter will be restored and normal monitoring will resume.",
            title="Amazon 403 recovered",
            priority=4,
        )
        return True


def find_available_shift_hours(page, max_hours: float) -> list[float]:
    """Find visible shifts at or below the selected weekly-hours limit."""
    try:
        if "/available-schedule/" not in page.url:
            return []
        body_text = page.locator("body").inner_text(timeout=3000)
    except Exception:
        return []

    if not SHIFT_COUNT_RE.search(body_text):
        return []

    matches = []
    for raw in SHIFT_HOURS_RE.findall(body_text):
        try:
            hours = float(raw)
        except ValueError:
            continue
        if hours <= max_hours:
            matches.append(hours)
    return sorted(set(matches), reverse=True)


def capture_shift_page_every_second(page, log) -> None:
    """Capture the live shift page once per second after a shift is detected."""
    try:
        original_url = page.url
    except Exception:
        original_url = ""

    log.warning(
        "Live shift screenshot recorder STARTED: saving one full-page screenshot every 1 second."
    )
    count = 0
    alarm_stopped = False

    while not page.is_closed():
        count += 1
        try:
            save_screenshot(page, shift_live_screenshot_name(count))
        except Exception as exc:
            log.warning("Could not save live shift screenshot #%s: %s", count, exc)
            break

        if count >= 5 and not alarm_stopped:
            stop_alarm()
            alarm_stopped = True

        page.wait_for_timeout(1000)

        try:
            if page.url != original_url:
                log.info("Live shift screenshot recorder stopped because the page changed.")
                break
            body_text = page.locator("body").inner_text(timeout=1500)
            if not SHIFT_COUNT_RE.search(body_text):
                log.info(
                    "Live shift screenshot recorder stopped because the shift card/count is no longer visible."
                )
                break
        except Exception:
            log.info("Live shift screenshot recorder stopped because the page is no longer readable.")
            break

    stop_alarm()
    log.info("Live shift screenshot recorder saved %s screenshot(s).", count)


def log_preferences(log, prefs: dict) -> None:
    log.info(
        "Amazon preferences applied: Desired hours=%s | Days=%s | Time=%s | Sorter=%s",
        prefs.get("hours"),
        prefs.get("days"),
        prefs.get("time"),
        prefs.get("sorter"),
    )
    if not prefs.get("day_option_applied"):
        log.warning(
            "Amazon did not expose a literal DAY preset in this Filter layout. "
            "The desired-hours and ANY-days filter were applied."
        )


def apply_hours_filter(page, desired_max_hours: float, log) -> dict:
    """Apply the Amazon UI filter at startup and after 403 recovery."""
    prefs = apply_amazon_preferences(
        page,
        max_hours=desired_max_hours,
        time_preference="DAY",
        sorter_name="Hours – most to least",
    )
    log_preferences(log, prefs)
    return prefs


def run():
    load_dotenv(ROOT / ".env")
    config = load_config()
    rules = config["rules"]
    configured_hours = float(rules.get("max_hours_per_week", 20))
    desired_max_hours = choose_desired_hours(configured_hours)

    rules["max_hours_per_week"] = desired_max_hours
    if desired_max_hours.is_integer():
        rules["preferred_hours_order"] = list(range(int(desired_max_hours), 3, -1))

    setup_logging()
    log = logging.getLogger("shift-catcher")

    interval = max(3, int(config.get("check_interval_seconds", 10)))
    auto_apply = env_bool("AUTO_APPLY", False)
    cdp_url = os.getenv("BRAVE_CDP_URL", "http://127.0.0.1:9222").strip()

    log.info("Starting Amazon Shift Catcher")
    log.info("AUTO_APPLY=%s", auto_apply)
    log.info("Check interval=%ss", interval)
    log.info("403 recovery interval=%ss", BLOCKED_RETRY_SECONDS)
    log.info("Desired maximum hours/week=%s", desired_max_hours)
    log.info(
        "Fast mode: Amazon hours filter is applied at startup and after 403 recovery only. "
        "Normal cycles only reload and inspect visible shifts with the Python hours guard."
    )
    log.info("Connecting to existing Brave session at %s", cdp_url)

    with sync_playwright() as p:
        try:
            browser = p.chromium.connect_over_cdp(cdp_url)
        except Exception as exc:
            raise RuntimeError(
                "Could not connect to Brave. Start Brave with remote debugging on port 9222, "
                "log in to Amazon Jobs, leave Brave open, then run this program."
            ) from exc

        page = choose_amazon_page(browser, config["my_jobs_url"])
        page.set_default_timeout(int(config.get("navigation_timeout_seconds", 30)) * 1000)

        try:
            reach_shift_page(page, config["my_jobs_url"], config.get("job_id") or None)
            wait_for_schedule_settled(page)

            blocked, excerpt = get_blocked_page_status(page)
            if blocked:
                if not recover_from_403(page, log, excerpt):
                    return

            prefs = apply_hours_filter(page, desired_max_hours, log)

            send_notification(
                "Amazon Shift Catcher connected to your existing Brave session.\n"
                f"Desired hours: {prefs['hours']}\n"
                f"Days: {prefs['days']}\n"
                f"Sorter: {prefs['sorter']}\n"
                f"Monitoring every {interval} seconds.\n"
                "Fast mode: filter drawer is NOT reopened on every normal refresh.\n"
                f"403 recovery test: every {BLOCKED_RETRY_SECONDS} seconds while blocked.\n"
                f"Auto Apply: {'ON' if auto_apply else 'OFF'}",
                title="Amazon monitor started",
                priority=3,
            )

            alerted_for_current_batch = False

            while True:
                if page.is_closed():
                    raise RuntimeError("The Amazon Jobs tab was closed.")

                blocked, excerpt = get_blocked_page_status(page)
                if blocked:
                    if not recover_from_403(page, log, excerpt):
                        break
                    prefs = apply_hours_filter(page, desired_max_hours, log)
                    alerted_for_current_batch = False
                    log.info(
                        "Normal %s-second fast monitoring resumed after 403 recovery.",
                        interval,
                    )
                    continue

                if page_has_security_challenge(page):
                    start_alarm()
                    save_screenshot(page, timestamp_name("security-challenge"))
                    send_notification(
                        "Amazon security or verification page detected. "
                        "Automation has stopped. Complete it manually.",
                        title="Amazon action required",
                        priority=5,
                    )
                    log.error("Security challenge detected. Stopping.")
                    break

                available_hours = find_available_shift_hours(page, desired_max_hours)
                if available_hours:
                    hours_text = ", ".join(f"{h:g}" for h in available_hours)
                    log.warning(
                        "AVAILABLE SHIFT DETECTED at/below %s h/week "
                        "(visible hours: %s). REFRESHING STOPPED immediately.",
                        f"{desired_max_hours:g}",
                        hours_text,
                    )
                    save_screenshot(page, timestamp_name("shift-freeze"))
                    start_alarm()
                    send_notification(
                        "Amazon shift available within your desired-hours limit.\n"
                        f"Visible weekly hours: {hours_text}\n"
                        f"Desired maximum: {desired_max_hours:g} hours/week\n\n"
                        "Refreshing has STOPPED. Live screenshots will now be saved every 1 second while the shift page remains visible.",
                        title="AMAZON SHIFT - REFRESH STOPPED",
                        priority=5,
                    )
                    capture_shift_page_every_second(page, log)
                    log.warning(
                        "Monitor stopped with the live shift page left open in Brave."
                    )
                    break

                cards = read_shift_cards(page)
                if cards:
                    log.info("%d visible shift action(s) detected", len(cards))

                    matches = []
                    for card in cards:
                        shift = parse_shift(card["text"])
                        ok, reasons = matches_rules(shift, rules)
                        log.info(
                            "Card %s | match=%s | hours=%s | days=%s | time=%s-%s | %s",
                            card["index"],
                            ok,
                            shift.hours_per_week,
                            shift.days,
                            shift.start_time,
                            shift.end_time,
                            "; ".join(reasons) if reasons else "accepted",
                        )
                        if ok:
                            matches.append((score_shift(shift, rules), card, shift))

                    if matches:
                        matches.sort(key=lambda item: item[0], reverse=True)
                        _, best_card, best_shift = matches[0]
                        details = (
                            f"Hours: {best_shift.hours_per_week or 'unknown'}\n"
                            f"Days: {', '.join(best_shift.days) or 'unknown'}\n"
                            f"Time: {best_shift.start_time or '?'} - {best_shift.end_time or '?'}"
                        )

                        if not alerted_for_current_batch:
                            start_alarm()
                            save_screenshot(page, timestamp_name("shift-found"))
                            send_notification(
                                f"{len(matches)} matching shift option(s) detected.\n"
                                "Refreshing is being stopped so you can act on the live page.",
                                title="AMAZON MATCHING SHIFT FOUND",
                                priority=5,
                            )
                            alerted_for_current_batch = True

                        if auto_apply:
                            log.warning("Matching shift found. Clicking Apply.")
                            save_screenshot(page, timestamp_name("before-apply"))
                            best_card["button"].click()
                            page.wait_for_timeout(1500)
                            save_screenshot(page, timestamp_name("after-apply"))
                            stop_alarm()
                            send_notification(
                                details
                                + "\n\nApply was clicked. Version 1 stops here. Check the next Amazon page.",
                                title="AMAZON SHIFT APPLY CLICKED",
                                priority=5,
                            )
                            log.info("Apply clicked. Version 1 complete.")
                            break

                        send_notification(
                            details
                            + "\n\nAUTO_APPLY is OFF. The live page has been left open and refreshing is stopped.",
                            title="MATCHING AMAZON SHIFT FOUND",
                            priority=5,
                        )
                        log.warning(
                            "Matching shift found with AUTO_APPLY OFF. Refreshing stopped."
                        )
                        capture_shift_page_every_second(page, log)
                        break

                    if alerted_for_current_batch:
                        stop_alarm()
                    alerted_for_current_batch = False
                    log.info(
                        "Shift cards are visible, but none match the configured rules."
                    )
                else:
                    if alerted_for_current_batch:
                        stop_alarm()
                    alerted_for_current_batch = False

                    url, title, empty_state, excerpt = get_page_status(page)
                    if empty_state:
                        log.info(
                            'No desired shift | Page="%s" | URL=%s | Empty state="%s"',
                            title,
                            url,
                            empty_state,
                        )
                    else:
                        log.warning(
                            'No desired shift | Page="%s" | URL=%s | '
                            'Expected Amazon empty-state text was NOT found | Visible text="%s"',
                            title,
                            url,
                            excerpt,
                        )

                time.sleep(interval)

                try:
                    reload_started = time.monotonic()

                    # FAST CYCLE: reload -> immediate 403 check -> settle -> inspect.
                    # Do not reopen/reset/apply the Filter drawer on normal cycles.
                    page.reload(wait_until="domcontentloaded", timeout=30000)

                    blocked, excerpt = get_blocked_page_status(page)
                    if blocked:
                        if not recover_from_403(page, log, excerpt):
                            break
                        prefs = apply_hours_filter(page, desired_max_hours, log)
                        alerted_for_current_batch = False
                        log.info(
                            "Normal %s-second fast monitoring resumed after 403 recovery.",
                            interval,
                        )
                        continue

                    wait_for_schedule_settled(page)

                    blocked, excerpt = get_blocked_page_status(page)
                    if blocked:
                        if not recover_from_403(page, log, excerpt):
                            break
                        prefs = apply_hours_filter(page, desired_max_hours, log)
                        alerted_for_current_batch = False
                        log.info(
                            "Normal %s-second fast monitoring resumed after 403 recovery.",
                            interval,
                        )
                        continue

                    reload_elapsed = time.monotonic() - reload_started
                    log.info(
                        "Fast reload ready in %.2fs; Filter drawer was not reopened.",
                        reload_elapsed,
                    )
                except Exception as exc:
                    log.exception(
                        "Fast refresh cycle failed. Monitoring is stopping rather than checking an unverified page."
                    )
                    send_notification(
                        "Amazon monitoring stopped because the fast refresh cycle failed.\n"
                        f"Error: {exc}\n\n"
                        "Check the Amazon page manually before restarting.",
                        title="Amazon monitor stopped - page error",
                        priority=5,
                    )
                    break

        except KeyboardInterrupt:
            log.info("Stopped by user.")
        except Exception as exc:
            log.exception("Fatal error")
            start_alarm()
            try:
                if not page.is_closed():
                    save_screenshot(page, timestamp_name("fatal-error"))
            except Exception:
                pass
            send_notification(
                f"Amazon Shift Catcher stopped with an error:\n{exc}",
                title="Amazon monitor stopped",
                priority=5,
            )
        finally:
            stop_alarm()
            log.info("Disconnected from automation. Brave has been left open.")
