def choose_amazon_page(browser, my_jobs_url: str):
    pages = []
    for context in browser.contexts:
        pages.extend(context.pages)
    for page in pages:
        try:
            if "jobsatamazon.co.uk" in page.url.lower():
                return page
        except Exception:
            pass
    if not browser.contexts:
        raise RuntimeError("No browser context found in the attached Brave session.")
    context = browser.contexts[0]
    page = context.new_page()
    page.goto(my_jobs_url, wait_until="domcontentloaded")
    return page


def get_page_status(page) -> tuple[str, str, str | None, str]:
    try:
        url = page.url
    except Exception:
        url = "<unavailable>"
    try:
        title = " ".join(page.title().split()) or "<no title>"
    except Exception:
        title = "<unavailable>"

    empty_state = None
    excerpt = "<unavailable>"
    try:
        body_text = page.locator("body").inner_text(timeout=3000)
        normalized = " ".join(body_text.split())
        excerpt = normalized[:500] if normalized else "<empty body>"
        match = EMPTY_SCHEDULE_RE.search(body_text)
        if match:
            empty_state = " ".join(match.group(0).split())
    except Exception:
        pass
    return url, title, empty_state, excerpt


def get_blocked_page_status(page) -> tuple[bool, str]:
    try:
        title = page.title()
    except Exception:
        title = ""
    try:
        body_text = page.locator("body").inner_text(timeout=3000)
    except Exception:
        body_text = ""

    combined = f"{title}\n{body_text}"
    blocked = bool(BLOCKED_PAGE_RE.search(combined))
    excerpt = " ".join(body_text.split())[:500]
    return blocked, excerpt


def get_passive_recovery_state(page) -> tuple[str, str]:
    """Inspect the already-loaded page without causing an automatic navigation/reload."""
    if page.is_closed():
        return "closed", ""

    try:
        url = page.url.lower()
    except Exception:
        url = ""

    try:
        title = page.title()
    except Exception:
        title = ""

    try:
        body_text = page.locator("body").inner_text(timeout=1000)
    except Exception:
        return "loading", ""

    excerpt = " ".join(body_text.split())[:500]
    combined = f"{title}\n{body_text}"
    if BLOCKED_PAGE_RE.search(combined):
        return "blocked", excerpt

    try:
        if page_has_security_challenge(page):
            return "security", excerpt
    except Exception:
        pass

    is_schedule_url = (
        "jobsatamazon.co.uk" in url and "/selfservice/schedule/" in url
    )
    if is_schedule_url and (
        SHIFT_COUNT_RE.search(body_text) or EMPTY_SCHEDULE_RE.search(body_text)
    ):
        return "schedule", excerpt

    normalized_lower = " ".join(body_text.lower().split())
    if (
        is_schedule_url
        and "select work shift" in normalized_lower
        and "loading..." not in normalized_lower
    ):
        return "schedule", excerpt

    return "loading", excerpt


def wait_for_passive_403_recovery(page, log, seconds: float) -> str:
    """Watch the current DOM so a user's manual refresh can be noticed immediately."""
    deadline = time.monotonic() + seconds

    while True:
        state, _ = get_passive_recovery_state(page)
        if state in {"schedule", "security", "closed"}:
            if state != "closed":
                log.warning(
                    "Passive 403 recovery watcher detected current page state=%s. "
                    "No automatic reload was needed.",
                    state,
                )
            return state

        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return "timeout"

        time.sleep(min(PASSIVE_RECOVERY_POLL_SECONDS, remaining))


def finish_403_recovery(
    log,
    metrics: SessionMetrics,
    started_monotonic: float,
    recovery_tests: int,
    source: str,
) -> bool:
    elapsed = time.monotonic() - started_monotonic
    metrics.record_403(elapsed, recovery_tests)
    metrics.transition(
        MonitorState.MONITORING,
        log,
        f"403 cleared after {int(elapsed)} seconds ({source})",
    )
    log.warning(
        "403 CLEARED after %s seconds; automatic recovery tests=%s; source=%s.",
        int(elapsed),
        recovery_tests,
        source,
    )
    tracked_notification(
        metrics,
        f"Amazon page is no longer showing the 403 after about {int(elapsed)} seconds.\n"
        f"Recovery source: {source}.\n"
        "Normal all-shift monitoring will resume now.",
        title="Amazon 403 cleared",
        priority=4,
    )
    return True


def recover_from_403(page, log, excerpt: str, metrics: SessionMetrics) -> bool:
    """
    Pause normal monitoring after a 403.

    The catcher makes at most one automatic test reload every 60 seconds. During each
    wait it passively inspects the already-loaded DOM once per second. This means a
    manual browser refresh that clears the 403 can be recognised without waiting for
    the next 60-second automatic test and without adding extra automatic reloads.
    """
    started_at = datetime.now()
    started_monotonic = time.monotonic()
    attempt = 0

    metrics.transition(MonitorState.PAUSED_403, log, "CloudFront 403 detected")
    log.error(
        "Amazon returned a 403/CloudFront blocked page at %s. Normal monitoring is paused.",
        started_at.strftime("%Y-%m-%d %H:%M:%S"),
    )
    if excerpt:
        log.error("Blocked-page excerpt: %s", excerpt)

    try:
        if not page.is_closed():
            tracked_screenshot(
                page,
                timestamp_name("amazon-403-blocked"),
                metrics,
            )
    except Exception:
        pass

    tracked_notification(
        metrics,
        "Amazon returned a 403 / Request blocked page.\n"
        "Normal monitoring is PAUSED.\n"
        f"The catcher will make no automatic reload for {BLOCKED_RETRY_SECONDS} seconds.\n"
        "If you manually refresh Brave and the normal shift page returns, the catcher will detect it and resume automatically.\n"
        f"If it stays blocked, one automatic recovery test is made every {BLOCKED_RETRY_SECONDS} seconds.",
        title="Amazon 403 - recovery mode",
        priority=5,
    )

    while True:
        log.warning(
            "403 recovery wait: no automatic reload for up to %s seconds. "
            "Passive current-page watcher is active every %.0f second(s); manual refresh is allowed.",
            BLOCKED_RETRY_SECONDS,
            PASSIVE_RECOVERY_POLL_SECONDS,
        )

        passive_state = wait_for_passive_403_recovery(
            page,
            log,
            BLOCKED_RETRY_SECONDS,
        )

        if passive_state == "closed":
            metrics.record_error("Amazon tab closed during 403 recovery")
            return False

        if passive_state == "security":
            return finish_403_recovery(
                log,
                metrics,
                started_monotonic,
                attempt,
                "current page left 403 and reached security/verification",
            )

        if passive_state == "schedule":
            try:
                wait_for_schedule_settled(page)
            except Exception as exc:
                log.warning(
                    "Current page appears recovered but has not fully settled yet: %s",
                    exc,
                )

            blocked, _ = get_blocked_page_status(page)
            if not blocked:
                return finish_403_recovery(
                    log,
                    metrics,
                    started_monotonic,
                    attempt,
                    "manual/current-page refresh detected",
                )

            log.warning(
                "The page briefly looked recovered but the 403 returned. Remaining in recovery mode."
            )
            metrics.transition(
                MonitorState.PAUSED_403,
                log,
                "403 returned after passive recovery check",
            )
            continue

        attempt += 1
        metrics.transition(
            MonitorState.RECOVERING,
            log,
            f"403 automatic recovery test {attempt}",
        )
        log.warning(
            "403 automatic recovery test %s: performing one reload after the quiet period.",
            attempt,
        )

        try:
            page.reload(wait_until="domcontentloaded", timeout=30000)
        except Exception as exc:
            metrics.record_error(exc)
            log.exception("403 recovery test reload failed: %s", exc)
            tracked_notification(
                metrics,
                f"Amazon 403 recovery test failed with a page error:\n{exc}\n\n"
                "Automatic monitoring has stopped. Check the page manually.",
                title="Amazon 403 recovery stopped",
                priority=5,
            )
            return False

        blocked, latest_excerpt = get_blocked_page_status(page)
        if blocked:
            metrics.transition(
                MonitorState.PAUSED_403,
                log,
                f"403 still active after automatic recovery test {attempt}",
            )
            log.warning(
                "403 is still present after automatic recovery test %s. "
                "Returning to passive recovery wait.",
                attempt,
            )
            if latest_excerpt:
                log.debug("Blocked-page excerpt: %s", latest_excerpt)
            continue

        try:
            wait_for_schedule_settled(page)
        except Exception as exc:
            log.warning("Page returned from 403 but did not settle normally yet: %s", exc)

        blocked, _ = get_blocked_page_status(page)
        if blocked:
            metrics.transition(
                MonitorState.PAUSED_403,
                log,
                "403 returned during automatic recovery verification",
            )
            continue

        return finish_403_recovery(
            log,
            metrics,
            started_monotonic,
            attempt,
            "automatic recovery reload",
        )


def find_all_available_shift_hours(page) -> list[float]:
    """Return all visible weekly-hours values; selected hours are not a limit."""
    try:
        if "/available-schedule/" not in page.url:
            return []
        body_text = page.locator("body").inner_text(timeout=3000)
    except Exception:
        return []

    if not SHIFT_COUNT_RE.search(body_text):
        return []

    result = []
    for raw in SHIFT_HOURS_RE.findall(body_text):
        try:
            result.append(float(raw))
        except ValueError:
            continue
    return result


def capture_shift_page_every_second(page, log, metrics: SessionMetrics) -> None:
    """Capture the live shift page once per second after a shift is detected."""
    try:
        original_url = page.url
    except Exception:
        original_url = ""

    log.warning(
        "Live shift screenshot recorder STARTED: saving one full-page screenshot every 1 second."
    )
    count = 0
    alarm_stopped = False

    while not page.is_closed():
        count += 1
        try:
            tracked_screenshot(
                page,
                shift_live_screenshot_name(count),
                metrics,
            )
        except Exception as exc:
            log.warning("Could not save live shift screenshot #%s: %s", count, exc)
            break

        if count >= 5 and not alarm_stopped:
            stop_alarm()
            alarm_stopped = True

        page.wait_for_timeout(1000)

        try:
            if page.url != original_url:
                log.info("Live shift screenshot recorder stopped because the page changed.")
                break
            body_text = page.locator("body").inner_text(timeout=1500)
            if not SHIFT_COUNT_RE.search(body_text):
                log.info(
                    "Live shift screenshot recorder stopped because the shift card/count is no longer visible."
                )
                break
        except Exception:
            log.info("Live shift screenshot recorder stopped because the page is no longer readable.")
            break

    stop_alarm()
    log.info("Live shift screenshot recorder saved %s screenshot(s).", count)


def handle_available_shifts(
    page,
    log,
    priority_hours: float,
    metrics: SessionMetrics,
) -> bool:
    """Detect all visible shifts, rank locally, highlight priority, and freeze page."""
    cards = read_visible_shift_cards(page)
    visible_hours = [card["hours"] for card in cards]

    if not visible_hours:
        visible_hours = find_all_available_shift_hours(page)
    if not visible_hours:
        return False

    ranked_hours = rank_hours(visible_hours, priority_hours)
    exact_count = sum(1 for value in visible_hours if value == priority_hours)
    metrics.record_shift_batch(len(visible_hours), exact_count)
    metrics.transition(
        MonitorState.SHIFT_FOUND,
        log,
        f"{len(visible_hours)} visible shift(s); {exact_count} exact-priority",
    )

    log.warning(
        "AVAILABLE SHIFT(S) DETECTED. Visible hours=%s | Local priority order=%s | "
        "Preferred=%sh. Amazon card order is NOT changed.",
        ", ".join(f"{h:g}h" for h in visible_hours),
        " -> ".join(f"{h:g}h" for h in ranked_hours),
        f"{priority_hours:g}",
    )

    if cards:
        highlighted = highlight_priority_shift_card(page, cards, priority_hours)
        if highlighted is None:
            try:
                cards[0]["element"].scroll_into_view_if_needed(timeout=1500)
            except Exception:
                pass

    tracked_screenshot(page, timestamp_name("shift-freeze"), metrics)
    start_alarm()

    if exact_count:
        message = (
            f"Amazon shift(s) available.\n"
            f"PRIORITY: {priority_hours:g} hours/week found ({exact_count}).\n"
            f"All visible hours: {', '.join(f'{h:g}h' for h in visible_hours)}\n\n"
            "Refreshing has STOPPED. The first exact-priority card was highlighted and scrolled into view when identifiable. "
            "Amazon's card order was not changed, so you can click the original card normally."
        )
        title = "AMAZON PRIORITY SHIFT FOUND"
    else:
        message = (
            f"Amazon shift(s) available, but no exact {priority_hours:g}h shift was visible.\n"
            f"Other visible hours: {', '.join(f'{h:g}h' for h in visible_hours)}\n\n"
            "Refreshing has STOPPED so you can choose one manually. Amazon's original cards were not rearranged."
        )
        title = "AMAZON SHIFT FOUND - OTHER HOURS"

    tracked_notification(metrics, message, title=title, priority=5)
    log.warning("Refreshing stopped so the live Amazon cards remain clickable.")
    capture_shift_page_every_second(page, log, metrics)
    return True


def run():
    load_dotenv(ROOT / ".env")
    config = load_config()
    configured_default = float(config.get("rules", {}).get("max_hours_per_week", 20))
    selected_priority_hours = choose_priority_hours(configured_default)

    setup_logging()
    log = logging.getLogger("shift-catcher")
    metrics = SessionMetrics()
    stop_reason = "normal shutdown"

    interval = max(3, int(config.get("check_interval_seconds", 10)))
    cdp_url = os.getenv("BRAVE_CDP_URL", "http://127.0.0.1:9222").strip()

    log.info("Starting Amazon Shift Catcher")
    log.info("Session ID=%s", metrics.session_id)
    log.info("Check interval=%ss", interval)
    log.info("403 automatic recovery interval=%ss", BLOCKED_RETRY_SECONDS)
    log.info(
        "403 passive recovery watcher=%.0fs DOM check; no automatic reload is added by the watcher.",
        PASSIVE_RECOVERY_POLL_SECONDS,
    )
    log.info("Priority weekly hours=%s", selected_priority_hours)
    log.info(
        "Priority mode: no desired-hours filter is imposed by the catcher. "
        "All shifts Amazon shows are monitored; exact priority hours are highlighted locally."
    )
    log.info("Connecting to existing Brave session at %s", cdp_url)

    with sync_playwright() as p:
        try:
            browser = p.chromium.connect_over_cdp(cdp_url)
        except Exception as exc:
            metrics.record_error(exc)
            metrics.transition(MonitorState.ERROR, log, "Could not connect to Brave")
            metrics.finish("browser connection failed")
            metrics.save(LOG_DIR)
            raise RuntimeError(
                "Could not connect to Brave. Start Brave with remote debugging on port 9222, "
                "log in to Amazon Jobs, leave Brave open, then run this program."
            ) from exc

        page = choose_amazon_page(browser, config["my_jobs_url"])
        page.set_default_timeout(int(config.get("navigation_timeout_seconds", 30)) * 1000)

        try:
            reach_shift_page(page, config["my_jobs_url"], config.get("job_id") or None)
            wait_for_schedule_settled(page)
            metrics.transition(MonitorState.MONITORING, log, "Shift page ready")

            blocked, excerpt = get_blocked_page_status(page)
            if blocked:
                if not recover_from_403(page, log, excerpt, metrics):
                    stop_reason = "403 recovery stopped"
                    return

            metrics.mark_check()
            if handle_available_shifts(page, log, selected_priority_hours, metrics):
                stop_reason = "shift found"
                return

            try:
                reset_amazon_filters_for_all_shifts(page)
            except Exception as exc:
                log.warning(
                    "Could not reset Amazon Filter to default/all-view state: %s. "
                    "Continuing without applying any new catcher hours filter.",
                    exc,
                )

            tracked_notification(
                metrics,
                "Amazon Shift Catcher connected to your existing Brave session.\n"
                f"Priority hours: {selected_priority_hours:g} hours/week\n"
                "Amazon desired-hours filter: not used by the catcher\n"
                "All visible Amazon shifts will be detected.\n"
                f"Monitoring interval: {interval} seconds.\n"
                f"403 automatic recovery test: every {BLOCKED_RETRY_SECONDS} seconds while blocked.\n"
                "Manual refresh during 403 recovery is detected automatically.",
                title="Amazon monitor started - priority mode",
                priority=3,
            )

            while True:
                if page.is_closed():
                    raise RuntimeError("The Amazon Jobs tab was closed.")

                metrics.mark_check()
                blocked, excerpt = get_blocked_page_status(page)
                if blocked:
                    if not recover_from_403(page, log, excerpt, metrics):
                        stop_reason = "403 recovery stopped"
                        break
                    continue

                if page_has_security_challenge(page):
                    metrics.transition(
                        MonitorState.SECURITY_CHECK,
                        log,
                        "Amazon security/verification page detected",
                    )
                    start_alarm()
                    tracked_screenshot(
                        page,
                        timestamp_name("security-challenge"),
                        metrics,
                    )
                    tracked_notification(
                        metrics,
                        "Amazon security or verification page detected. "
                        "Automation has stopped. Complete it manually.",
                        title="Amazon action required",
                        priority=5,
                    )
                    stop_reason = "security check"
                    break

                if handle_available_shifts(page, log, selected_priority_hours, metrics):
                    stop_reason = "shift found"
                    break

                url, title, empty_state, excerpt = get_page_status(page)
                if empty_state:
                    log.info(
                        'No shift | Page="%s" | URL=%s | Empty state="%s"',
                        title,
                        url,
                        empty_state,
                    )
                else:
                    log.warning(
                        'No shift detected | Page="%s" | URL=%s | '
                        'Expected Amazon empty-state text was NOT found | Visible text="%s"',
                        title,
                        url,
                        excerpt,
                    )

                time.sleep(interval)

                try:
                    reload_started = time.monotonic()
                    page.reload(wait_until="domcontentloaded", timeout=30000)

                    blocked, excerpt = get_blocked_page_status(page)
                    if blocked:
                        metrics.record_reload(time.monotonic() - reload_started)
                        if not recover_from_403(page, log, excerpt, metrics):
                            stop_reason = "403 recovery stopped"
                            break
                        continue

                    wait_for_schedule_settled(page)

                    blocked, excerpt = get_blocked_page_status(page)
                    reload_elapsed = time.monotonic() - reload_started
                    metrics.record_reload(reload_elapsed)

                    if blocked:
                        if not recover_from_403(page, log, excerpt, metrics):
                            stop_reason = "403 recovery stopped"
                            break
                        continue

                    log.info(
                        "Fast reload ready in %.2fs; no hours filter was applied.",
                        reload_elapsed,
                    )
                except Exception as exc:
                    metrics.record_error(exc)
                    metrics.transition(
                        MonitorState.ERROR,
                        log,
                        "Fast refresh cycle failed",
                    )
                    log.exception(
                        "Fast refresh cycle failed. Monitoring is stopping rather than checking an unverified page."
                    )
                    tracked_notification(
                        metrics,
                        "Amazon monitoring stopped because the fast refresh cycle failed.\n"
                        f"Error: {exc}\n\n"
                        "Check the Amazon page manually before restarting.",
                        title="Amazon monitor stopped - page error",
                        priority=5,
                    )
                    stop_reason = "refresh error"
                    break

        except KeyboardInterrupt:
            stop_reason = "stopped by user"
            log.info("Stopped by user.")
        except Exception as exc:
            stop_reason = "fatal error"
            metrics.record_error(exc)
            metrics.transition(MonitorState.ERROR, log, str(exc))
            log.exception("Fatal error")
            start_alarm()
            try:
                if not page.is_closed():
                    tracked_screenshot(page, timestamp_name("fatal-error"), metrics)
            except Exception:
                pass
            tracked_notification(
                metrics,
                f"Amazon Shift Catcher stopped with an error:\n{exc}",
                title="Amazon monitor stopped",
                priority=5,
            )
        finally:
            stop_alarm()
            metrics.transition(MonitorState.STOPPED, log, stop_reason)
            metrics.finish(stop_reason)
            try:
                session_path, latest_path = metrics.save(LOG_DIR)
                summary = metrics.to_dict()
                log.info(
                    "Session metrics saved: %s | checks=%s | avg_check=%.2fs | "
                    "avg_reload=%.2fs | 403s=%s | avg_403=%.2fs | shift_batches=%s | screenshots=%s",
                    session_path.name,
                    summary["checks_total"],
                    summary["average_check_interval_seconds"],
                    summary["average_reload_seconds"],
                    summary["403_count"],
                    summary["403_average_duration_seconds"],
                    summary["shift_batches_seen"],
                    summary["screenshots_saved"],
                )
                log.info("Latest metrics snapshot: %s", latest_path)
            except Exception as exc:
                log.warning("Could not save session metrics: %s", exc)
            log.info("Disconnected from automation. Brave has been left open.")
